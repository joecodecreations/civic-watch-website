def plan(data: dict) -> dict[str, str]:
    """Relative path -> file text for everything this build owns."""
    files: dict[str, str] = {}
    for number in sorted(set(data.get("videos") or []), key=int):
        files[f"{number}/index.html"] = page(data, "video", number=number)
    for slug in data["bio"]:
        files[f"{slug}/index.html"] = page(data, "bio", slug=slug)
    files["free/index.html"] = page(data, "bio")
    files["go/index.html"] = page(data, "dynamic")
    codes = {
        "version": 1,
        "updated": str(data.get("generated_at", ""))[:10],
        "codes": [
            {k: entry.get(k, "") for k in ("code", "label", "grants", "starts", "ends")}
            for entry in data.get("game_codes") or []
        ],
    }
    files["promo/codes.json"] = json.dumps(codes, indent=2) + "\n"
    return files


def main(argv: list[str]) -> int:
    check = "--check" in argv
    try:
        data = load()
    except (OSError, json.JSONDecodeError, LinksError) as exc:
        print(f"FAIL: {exc}")
        return 1
    files = plan(data)
    dirs = sorted({path.split("/")[0] for path in files if path.endswith("/index.html")})
    previous = json.loads(MANIFEST.read_text()).get("dirs", []) if MANIFEST.exists() else []
    stale = [d for d in previous if d not in dirs]
    manifest = json.dumps({"dirs": dirs}, indent=2) + "\n"
    if check:
        drift = [p for p, text in files.items() if not (ROOT / p).exists() or (ROOT / p).read_text() != text]
        drift += [d + "/" for d in stale if (ROOT / d).exists()]
        if not MANIFEST.exists() or MANIFEST.read_text() != manifest:
            drift.append("promo/generated.json")
        if drift:
            print("FAIL: promo pages are out of date; run python3 scripts/build_promo.py\n  " + "\n  ".join(drift[:20]))
            return 1
        print(f"PASS: {len(dirs)} promo pages match promo/links.json")
        return 0
    for d in dirs:
        target = ROOT / d / "index.html"
        if target.exists() and MARKER not in target.read_text():
            print(f"FAIL: /{d}/ already exists and was not made by this script; pick another slug")
            return 1
    for d in stale:
        target = ROOT / d
        index = target / "index.html"
        if index.exists() and MARKER in index.read_text() and [p.name for p in target.iterdir()] == ["index.html"]:
            shutil.rmtree(target)
    for path, text in files.items():
        target = ROOT / path
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text() != text:
            target.write_text(text)
    MANIFEST.write_text(manifest)
    print(f"Built {len(dirs)} promo pages ({len(data.get('videos') or [])} videos, {len(data['bio'])} bio links, free, go) "
          f"and promo/codes.json ({len(data.get('game_codes') or [])} codes). Removed {len(stale)} stale.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
