"""Build the promo link pages from promo/links.json.

promo/links.json is written by the ValuxGamesMarketing studio (`python3 scripts/promo.py sync`);
edit the studio's config/promo.json rather than this file's output. This script writes:

- /<number>/index.html for every promo video (the number is the studio's VG number: VG-0412 -> /412/)
- /<slug>/index.html for each bio link (/tt/, /yt/, /ig/, /fb/, /x/) and /free/
- /go/index.html, the fallback that 404.html sends unknown numbers to (/go/?c=412)
- promo/codes.json, the reward codes Civic Watch's Android "Redeem code" box accepts
- promo/generated.json, the manifest used to remove pages that are no longer listed

Usage: python3 scripts/build_promo.py [--check]
--check exits 1 if the generated files on disk differ from what links.json would produce.
"""
from __future__ import annotations

import html
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LINKS = ROOT / "promo" / "links.json"
CODES = ROOT / "promo" / "codes.json"
MANIFEST = ROOT / "promo" / "generated.json"
TAG = "G-5CKV6VD9KM"
MARKER = "Promo link page generated by scripts/build_promo.py"
OG_IMAGE = "/assets/loading/73_pearl_brenda_hank_watch.webp"
RESERVED = {"assets", "css", "js", "play", "promo", "scripts", ".github", ".git"}
SLUG = re.compile(r"^[a-z0-9-]{1,24}$")
NUMBER = re.compile(r"^[1-9][0-9]{0,5}$")
CODE = re.compile(r"^[A-Z0-9]{3,64}$")
DATE = re.compile(r"^(\d{4}-\d{2}-\d{2})?$")
GRANT_KINDS = {"skin", "trail", "character"}


class LinksError(ValueError):
    pass


def load() -> dict:
    data = json.loads(LINKS.read_text())
    validate(data)
    return data


def validate(data: dict) -> None:
    def need(cond: bool, message: str) -> None:
        if not cond:
            raise LinksError(f"promo/links.json: {message}")

    need(data.get("version") == 1, "version must be 1")
    need(str(data.get("site", "")).startswith("https://"), "site must be an https URL")
    apple, play, reward = data.get("apple") or {}, data.get("play") or {}, data.get("reward") or {}
    need(re.fullmatch(r"\d{6,12}", str(apple.get("app_id", ""))) is not None, "apple.app_id must be the numeric App Store id")
    need(re.fullmatch(r"\d*", str(apple.get("pt", ""))) is not None, "apple.pt must be the numeric provider token or empty")
    need(str(apple.get("store_url", "")).startswith("https://apps.apple.com/"), "apple.store_url must be an App Store URL")
    need(re.fullmatch(r"[a-z][a-z0-9_.]+", str(play.get("package", ""))) is not None, "play.package must be the Android package")
    for key in ("apple_code", "android_code"):
        value = str(reward.get(key, ""))
        need(value == "" or CODE.fullmatch(value) is not None, f"reward.{key} must be 3-64 letters/digits or empty")
    for key in ("starts", "ends"):
        need(DATE.fullmatch(str(reward.get(key, ""))) is not None, f"reward.{key} must be YYYY-MM-DD or empty")
    need(bool(reward.get("name")) and bool(reward.get("label")), "reward needs name and label")
    need(str(reward.get("image", "")).startswith("/promo/"), "reward.image must live under /promo/")
    bio = data.get("bio") or {}
    need(isinstance(bio, dict) and bio, "bio must map slugs to platform names")
    for slug in bio:
        need(SLUG.fullmatch(slug) is not None and slug not in RESERVED and not slug.isdigit(), f"bad bio slug {slug!r}")
    videos = data.get("videos") or []
    need(isinstance(videos, list), "videos must be a list")
    for number in videos:
        need(isinstance(number, str) and NUMBER.fullmatch(number) is not None, f"bad video number {number!r}")
    for entry in data.get("game_codes") or []:
        need(CODE.fullmatch(str(entry.get("code", ""))) is not None, f"bad game code {entry.get('code')!r}")
        need(bool(entry.get("label")), f"game code {entry.get('code')} needs a label")
        grants = entry.get("grants") or []
        need(bool(grants) and all(g.get("kind") in GRANT_KINDS and g.get("id") for g in grants),
             f"game code {entry.get('code')} grants must be skin/trail/character items")
        for key in ("starts", "ends"):
            need(DATE.fullmatch(str(entry.get(key, ""))) is not None, f"game code {entry.get('code')} {key} must be YYYY-MM-DD or empty")


def asset(path: str) -> str:
    """/promo/promo.css?v=<content hash>, so a rebuilt page never pairs with a cached older script or style."""
    import hashlib
    digest = hashlib.sha1((ROOT / path.lstrip("/")).read_bytes()).hexdigest()[:10]
    return f"{path}?v={digest}"


def esc(text: str) -> str:
    return html.escape(str(text), quote=True)


def via_script(default: str) -> str:
    """Settle `via` before gtag('config') so the page_view URL carries ?via= (README "Promo links")."""
    return (
        "<script>\n"
        "      (function () {\n"
        f"        if (/^(127\\.0\\.0\\.1|localhost)$/.test(location.hostname)) window[\"ga-disable-{TAG}\"] = true; // local preview\n"
        f"        var page = {json.dumps(default)}, ok = /^[a-z0-9-]{{1,24}}$/;\n"
        "        var q = new URLSearchParams(location.search), via = (q.get(\"via\") || \"\").toLowerCase();\n"
        "        if (!ok.test(via)) via = page;\n"
        "        if (!via) {\n"
        "          var ua = navigator.userAgent;\n"
        "          via = /BytedanceWebview|musical_ly|TikTok/i.test(ua) ? \"tt\" : /Instagram/.test(ua) ? \"ig\"\n"
        "            : /FBAN|FBAV|FB_IAB|FBIOS/.test(ua) ? \"fb\" : /Twitter/i.test(ua) ? \"x\"\n"
        "            : /Snapchat/i.test(ua) ? \"snap\" : /Reddit/i.test(ua) ? \"reddit\" : \"\";\n"
        "        }\n"
        "        if (!via && document.referrer) {\n"
        "          var h = \"\";\n"
        "          try { h = new URL(document.referrer).hostname.replace(/^(www|m|l|lm|out)\\./, \"\"); } catch (e) {}\n"
        "          via = /^youtu(be\\.com|\\.be)$/.test(h) ? \"yt\" : /^(t\\.co|x\\.com|twitter\\.com)$/.test(h) ? \"x\"\n"
        "            : /^(facebook\\.com|fb\\.com|fb\\.me)$/.test(h) ? \"fb\" : h === \"instagram.com\" ? \"ig\"\n"
        "            : h === \"tiktok.com\" ? \"tt\" : h === \"reddit.com\" ? \"reddit\"\n"
        "            : /^discord(app)?\\.com$/.test(h) ? \"discord\" : /(^|\\.)(google\\.|bing\\.com|duckduckgo\\.com)/.test(h) ? \"search\" : \"\";\n"
        "        }\n"
        "        via = via || \"direct\";\n"
        "        window.__promoVia = via;\n"
        "        if (q.get(\"via\") !== via) {\n"
        "          q.set(\"via\", via);\n"
        "          history.replaceState(null, \"\", location.pathname + \"?\" + q.toString() + location.hash);\n"
        "        }\n"
        "      })();\n"
        "    </script>"
    )


